# Build the Earth Jukebox globe page.
#   playground/breathing.html      page + shared assets only (land mask, Blue Marble backdrop)
#   playground/stories/<id>.js     one data file per story, loaded with a <script> tag when the story is picked
#                                  (works from file:// in Safari and Chrome; images stay data: URIs so WebGL can use them)
#   playground/audio/*.js          music engine loops (default rhythm only + synth layers), loaded on the first Play tap
# The 10 new stories' files are written by data-pipeline/<id>.py; this script writes breathing.js and wuhan.js.
import base64, json, pathlib, re, shutil

root = pathlib.Path(__file__).resolve().parent
repo = root.parent.parent
play = root.parent
data = repo / "data" / "c4"
stories = play / "stories"; stories.mkdir(exist_ok=True)
audio = play / "audio"; audio.mkdir(exist_ok=True)
b64 = lambda p: base64.b64encode(p.read_bytes()).decode()


def story_js(sid, obj):
    out = stories / f"{sid}.js"
    out.write_text(f"// generated by playground/c4-src/build.py, do not edit\n(window.STORY_DATA = window.STORY_DATA || {{}})['{sid}'] = {json.dumps(obj, separators=(',', ':'))};\n")
    print(out.relative_to(repo), round(out.stat().st_size / 1e6, 2), "MB")


# ---- C4 The Planet Breathing (MODIS NDVI 2021 to 2023 + Mauna Loa CO2)
# three years when the 2022/2023 maps and the 36-month tree file are present; otherwise the 2021-only cycle
T3 = data / "trees_0p5deg_2021_2023.bin"
YEARS = (2021, 2022, 2023) if T3.exists() and all((data / "textures" / f"ndvi_{y}_{m:02d}.jpg").exists() for y in (2022, 2023) for m in range(1, 13)) else (2021,)
story_js("breathing", {
    "timebase": "day", "step_s": 86400, "t0": "2021-01-01T00:00Z", "n": 365 * len(YEARS),   # 2021 to 2023: 1095 days (no leap day)
    "tex": ["data:image/jpeg;base64," + b64(data / "textures" / f"ndvi_{y}_{m:02d}.jpg") for y in YEARS for m in range(1, 13)],
    **({"tex_m0": "2021-01", "tree_m0": "2021-01", "tree_months": 36} if len(YEARS) == 3 else {}),
    "trees": b64(T3 if len(YEARS) == 3 else data / "trees_0p5deg_2021.bin"),
    "series": json.loads((data / "series.json").read_text()),   # full Mauna Loa record kept; ndvi_3y + correlations_3y for the 3 years
})
# ---- E9 Wuhan lockdown (OMI NO2, 2015-19 baseline aligned on Lunar New Year)
wd = repo / "data" / "wuhan"
ws = json.loads((wd / "series.json").read_text())
story_js("wuhan", {
    "timebase": "day", "step_s": 86400, "t0": ws["dates"][0] + "T00:00Z", "n": ws["days"],
    "no2": b64(wd / "no2_daily_2020.bin"),
    "series": ws,
    # NASA GIBS BlueMarble_ShadedRelief_Bathymetry, 4096x4096, lat 20.925..43.075, lon 103.925..126.075 (backdrop only)
    "basemap": "data:image/jpeg;base64," + b64(wd / "basemap_4096.jpg"),
    "basemap_bbox": [20.925, 43.075, 103.925, 126.075],
})

# ---- music: only the default rhythm's 5 loops (the full bundle has 6 rhythms, 13.7 MB) + synth layers + mix
me = repo / "music-engine" / "prototype"
cfg = (me / "engine-config.js").read_text()
rhythm = re.search(r'"rhythm":\s*"([^"]+)"', cfg).group(1)
lb = (me / "loop-bounces.js").read_text()
m = re.search(r'name:\s*"' + re.escape(rhythm) + r'",\s*loops:\s*\[(.*?)\]', lb, re.S)
loops = re.findall(r'"([A-Za-z0-9+/=]{1000,})"', m.group(1))
assert len(loops) == 5, f"expected 5 loops for {rhythm}, got {len(loops)}"
(audio / "drums.js").write_text(f"// {rhythm}: 5 intensities, 8 bars at 96 BPM, base64 AAC (from music-engine/prototype/loop-bounces.js)\n"
                                f"window.EJ_DRUMS = {{name:{json.dumps(rhythm)}, loops:{json.dumps(loops)}}};\n")
shutil.copyfile(me / "synth-layers.js", audio / "synth-layers.js")
shutil.copyfile(me / "engine-config.js", audio / "engine-config.js")
for f in ("drums.js", "synth-layers.js", "engine-config.js"):
    print("audio/" + f, round((audio / f).stat().st_size / 1e6, 2), "MB")

# ---- page: shared assets only
shared = {
    "mask": "data:image/png;base64," + b64(data / "textures" / "landmask.png"),
    # NASA GIBS BlueMarble_ShadedRelief_Bathymetry, global 4096x2048 (true-colour backdrop)
    "basemap": "data:image/jpeg;base64," + b64(repo / "data" / "basemap" / "bluemarble_4096x2048.jpg"),
}
html = (root / "template.html").read_text().replace("/*__SHARED__*/", json.dumps(shared))
out = play / "breathing.html"   # all stories live in this one page; pick on the landing screen or #<story id>
out.write_text(html)
print(out.relative_to(repo), round(len(html) / 1e6, 2), "MB")
